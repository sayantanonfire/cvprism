def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def make_manifest(cv: dict, bullets: list[dict], out_dir: Path, built: str, role: str) -> dict:
    main = next((n for n in ("cv.pdf", "cv.docx", "cv.md") if (out_dir / n).exists()), "cv.md")
    return {
        "v": 1,
        "name": cv["person"]["name"],
        "headline": cv.get("headline"),
        "role": role,
        "built": built,
        "file": main,
        "sha256": sha256_file(out_dir / main),
        "files": {n: sha256_file(out_dir / n) for n in ("cv.pdf", "cv.docx", "cv.md") if (out_dir / n).exists()},
        "bullets": bullets,
    }


def verify_pdf(path: Path, manifest: dict) -> bool:
    digest = sha256_file(path)
    return digest == manifest.get("sha256") or digest in (manifest.get("files") or {}).values()


def qr_svg(url: str) -> str:
    import io

    import segno

    buf = io.BytesIO()
    segno.make(url, error="m").save(buf, kind="svg", scale=4, border=2, dark="#1A2230")
    return buf.getvalue().decode("utf-8")


def qr_png(url: str, path: Path) -> Path:
    import segno

    segno.make(url, error="m").save(str(path), kind="png", scale=6, border=2, dark="#1A2230")
    return path


def page_html(manifest: dict, page_url: str | None) -> str:
    e = html.escape
    rows = []
    for b in manifest["bullets"]:
        if b.get("links"):
            proof = " ".join(f'<a href="{e(u)}" rel="noopener">{e(short_url(u))}</a>' for u in b["links"])
        elif b.get("label"):
            proof = f'<span class="muted">{e(b["label"])}</span>'
        else:
            proof = f'<span class="muted">{e(no_link_text(b.get("level")))}</span>'
        rows.append(f"<tr><td>{e(b['text'])}</td><td class='lvl'>{e(LEVEL_LABEL.get(b['level'], b['level']))}</td>"
                    f"<td>{proof}</td><td class='muted'>{e(b.get('date') or '')}</td></tr>")
    qr = '<img src="qr.svg" alt="QR code linking to this page">' if page_url else ""
    files = "".join(f"<div><code>{e(n)}</code> <code>{e(h)}</code></div>" for n, h in manifest.get("files", {}).items())
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Verify: {e(manifest['name'])}'s CV</title><style>{PAGE_CSS}</style></head>
<body><div class="spectrum" aria-hidden="true"></div><main>
<h1>{e(manifest['name'])}</h1>
<p class="lede">{e(manifest.get('headline') or '')}. CV built by cvprism on {e(manifest['built'][:10])}. Every line below
shows the proof behind it.</p>
<div class="fp">{qr}<div><b>Fingerprint (SHA-256)</b>
<p class="muted">This proves this file was not changed after cvprism built it. It does not prove the claims themselves:
the public links do. Check with <code>cvprism verify cv.pdf --manifest {e((page_url or '').rstrip('/') + '/manifest.json')}</code>
or any SHA-256 tool.</p>{files}</div></div>
<table><thead><tr><th>CV line</th><th>Proof level</th><th>Proof</th><th>Captured</th></tr></thead>
<tbody>{''.join(rows)}</tbody></table>
<p class="muted">Private and local work is listed without links: the skill is real, the code is not public.
Generated by <a href="https://github.com/sayantanonfire/cvprism">cvprism</a>.</p>
</main></body></html>
"""


def write_site(manifest: dict, dest: Path, page_url: str | None, src_dir: Path | None = None) -> Path:
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "index.html").write_text(page_html(manifest, page_url), encoding="utf-8")
    if src_dir is not None and (Path(src_dir) / "manifest.json").exists():
        # copy the exact bytes so a signature over the build's manifest stays valid
        shutil.copyfile(Path(src_dir) / "manifest.json", dest / "manifest.json")
        sig = Path(src_dir) / "manifest.json.sig"
        if sig.exists():
            shutil.copyfile(sig, dest / "manifest.json.sig")
        else:
            (dest / "manifest.json.sig").unlink(missing_ok=True)
    else:
        (dest / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n",
                                            encoding="utf-8")
    if page_url:
        (dest / "qr.svg").write_text(qr_svg(page_url), encoding="utf-8")
    return dest


_ID = ["-c", "user.name=cvprism", "-c", "user.email=cvprism@localhost", "-c", "commit.gpgsign=false"]


def publish(manifest: dict, verify_cfg: dict, work_dir: Path, src_dir: Path | None = None) -> str:
    """Write the site into a clone of the user's Pages repo and push. Returns the page URL."""
    repo, sub = verify_cfg["repo"], (verify_cfg.get("path") or "cv").strip("/")

    def git(*a, check=True):
        r = subprocess.run(["git", *_ID, "-C", str(work_dir), *a], capture_output=True, text=True, timeout=120)
        if check and r.returncode != 0:
            raise RuntimeError(f"git {' '.join(a[:2])}: {(r.stderr or r.stdout).strip()[:300]}")
        return r

    if not (work_dir / ".git").is_dir():
        shutil.rmtree(work_dir, ignore_errors=True)
        r = subprocess.run(["git", "clone", "-q", repo, str(work_dir)], capture_output=True, text=True, timeout=180)
        if r.returncode != 0:
            raise RuntimeError(f"could not clone {repo}: {r.stderr.strip()[:300]}")
    else:
        git("pull", "-q", "--rebase", check=False)
    branch = git("symbolic-ref", "--short", "HEAD", check=False).stdout.strip() or "main"
    write_site(manifest, work_dir / sub, verify_cfg.get("url"), src_dir)
    git("add", "-A")
    if git("diff", "--cached", "--quiet", check=False).returncode != 0:
        git("commit", "-q", "-m", f"cvprism: verify page for {manifest['role']} ({manifest['built'][:10]})")
        git("push", "-q", "origin", f"HEAD:{branch}")
    return verify_cfg.get("url") or ""
