"""Global git hooks dispatcher with chaining (ADR-008)."""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

from .. import paths

CLIENT_HOOKS = (
    "applypatch-msg", "pre-applypatch", "post-applypatch", "pre-commit", "pre-merge-commit",
    "prepare-commit-msg", "commit-msg", "post-commit", "pre-rebase", "post-checkout", "post-merge",
    "pre-push", "post-rewrite", "pre-auto-gc", "push-to-checkout", "sendemail-validate",
    "reference-transaction", "post-index-change",
)
STDIN_HOOKS = ("pre-push", "post-rewrite", "reference-transaction")


def hooks_dir() -> Path:
    return paths.home() / "git-hooks"


def _state() -> Path:
    return paths.home() / "state" / "git-install.json"


def _git_global(*args: str, check: bool = False) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "config", "--global", *args], capture_output=True, text=True, check=check)


def _sh_quote(s: str) -> str:
    return "'" + s.replace("'", "'\"'\"'") + "'"


def dispatcher_script(handler: list[str], prev: str | None) -> str:
    handler_cmd = " ".join(_sh_quote(Path(handler[0]).as_posix() if i == 0 else a) for i, a in enumerate(handler))
    stdin_case = "|".join(STDIN_HOOKS)
    return f"""#!/bin/sh
# cvprism git hook dispatcher (ADR-008). Generated by `cvprism install`; do not edit.
name="$(basename "$0")"
buffered=0
case "$name" in {stdin_case}) input="$(cat)"; buffered=1 ;; esac
run() {{
  if [ "$buffered" = 1 ]; then printf '%s\\n' "$input" | "$@"; else "$@"; fi
}}
if [ "$name" = "post-commit" ] && [ -z "$CVPRISM_EXTRACTING" ]; then
  {handler_cmd} git-post-commit >/dev/null 2>&1 </dev/null || true
fi
gitdir="$(git rev-parse --git-common-dir 2>/dev/null)"
if [ -n "$gitdir" ] && [ -f "$gitdir/hooks/$name" ] && [ -x "$gitdir/hooks/$name" ]; then
  run "$gitdir/hooks/$name" "$@" || exit $?
fi
prev={_sh_quote(prev or "")}
if [ -n "$prev" ] && [ -f "$prev/$name" ] && [ -x "$prev/$name" ]; then
  run "$prev/$name" "$@" || exit $?
fi
exit 0
"""


def install(handler: list[str]) -> Path:
    """handler: argv that runs the hook entry point, e.g. ['/venv/bin/cvprism-hook']."""
    d = hooks_dir()
    current = _git_global("core.hooksPath").stdout.strip() or None
    state = json.loads(_state().read_text(encoding="utf-8")) if _state().exists() else None
    prev = state["prev"] if state else (current if current and Path(current) != d else None)
    d.mkdir(parents=True, exist_ok=True)
    script = dispatcher_script(handler, prev)
    for name in CLIENT_HOOKS:
        p = d / name
        p.write_text(script, encoding="utf-8", newline="\n")
        p.chmod(0o755)
    _state().parent.mkdir(parents=True, exist_ok=True)
    _state().write_text(json.dumps({"prev": prev}), encoding="utf-8")
    _git_global("core.hooksPath", d.as_posix(), check=True)
    return d


def uninstall() -> None:
    if _state().exists():
        prev = json.loads(_state().read_text(encoding="utf-8")).get("prev")
        current = _git_global("core.hooksPath").stdout.strip()
        if current and Path(current) == hooks_dir():
            if prev:
                _git_global("core.hooksPath", prev, check=True)
            else:
                _git_global("--unset", "core.hooksPath")
        _state().unlink()
    shutil.rmtree(hooks_dir(), ignore_errors=True)


def installed() -> bool:
    current = _git_global("core.hooksPath").stdout.strip()
    return bool(current) and Path(current) == hooks_dir()


def repos_overriding_hooks(roots: list[Path], max_depth: int = 4) -> list[Path]:
    """Repos whose local core.hooksPath (e.g. husky) bypasses the global dispatcher."""
    found = []

    def walk(d: Path, depth: int) -> None:
        if depth > max_depth or not d.is_dir():
            return
        if (d / ".git").exists():
            out = subprocess.run(["git", "-C", str(d), "config", "--local", "core.hooksPath"],
                                 capture_output=True, text=True)
            if out.returncode == 0 and out.stdout.strip():
                found.append(d)
            return
        try:
            children = sorted(c for c in d.iterdir() if c.is_dir() and not c.name.startswith((".", "node_modules")))
        except OSError:
            return
        for c in children:
            walk(c, depth + 1)

    for r in roots:
        walk(Path(r), 0)
    return found
